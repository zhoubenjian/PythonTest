a = 1.414
b = 2.236
c = 2.732

print(f'a + b = {(a + b):.2f}')     # a + b = 3.65

print('a * c = %.2f' % (a * c))     # a * c = 3.86

# 浮点除法
print('b / c =', format(b / c, '.2f'))      # b / c = 0.82

# 地板除法
print('b // c = {:.2f}'.format(b // c))     # b // c = 0.00

# 取模（余）运算
print('100 % 19 =', format(100 % 19))       # 100 % 19 = 5
