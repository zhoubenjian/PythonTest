'''
贝叶斯公式（Bayes' Theorem）
    P(H|D) = P(D|H) * P_H / P(D_H)
'''


'''
某种病患病率 0.1%，检测准确率 99%。你检测出阳性——实际患病的概率只有约 9%
'''
# 患病率（先验概率）：0.1%
P_H = 0.001
# 检测准确率（后验概率）：99%
P_D_H = 0.99
# 检测错误率（后验概率）：1%
P_N_H = 0.01

# 检测阳性，实际患病
P_E = P_D_H * P_H + P_N_H * (1 - P_H)
P_H_E = P_D_H * P_H / P_E
print(f'先验患病概率：{P_H:.1%}')              # 0.1%
print(f'检测阳性后，实际患病概率：{P_H_E:.1%}')  # 9.0%
