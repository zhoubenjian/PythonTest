a = 2 ** (1/2)
b = 3 ** (1/2)
c = 5 ** (1/2)
d = 7 ** (1/2)


print('a ≈ %.3f' % a)           # 1.414
print('b ≈ {:.3f}'.format(b))   # 1.732
print(f'c ≈ {c:.3f}')           # 2.236
print('d ≈', f'{d:.3f}')        # 2.646

print('-' * 50)

# /：普通除法
print('10 / 3 =', 10 / 3)       # 3.3333333333333335
# //：整除(只保留整数部分)
print('10 // 3 =', 10 // 3)     # 3
# %：取余(取模)
print('10 % 3 =', 10 % 3)       # 1

print('-' * 50)

# **：乘方
print('10 ** 3 =', 10 ** 3)     # 1000
