'''
基础数据类型
    数值类型 (Numeric)：
        整数 (int)：表示没有小数部分的数字。Python 的整数没有大小限制，可以表示任意大的数字。
        浮点数 (float)：表示带有小数点的数字。支持科学计数法（如 2.5e-3）。⚠️ 注意精度问题：由于计算机二进制存储的限制，浮点数运算可能存在微小误差。例如 0.1 + 0.2 的结果是 0.30000000000000004 而非 0.3
        布尔值 (bool)：表示逻辑上的“真”与“假”，只有 True 和 False 两个值。

    序列类型 (Sequence)：
        字符串 (str)：用于存储文本，是不可变类型。
        列表 (list)：有序且可变的序列，可以存储任意类型的数据
        元组 (tuple)：有序且不可变的序列

    映射与集合类型：
        字典 (dict)：键值对 (Key-Value) 的集合，属于可变类型。
        集合 (set)：无序且不重复的元素集合，属于可变类型。

    空值类型 (NoneType)：
        None：表示“无”或“空”，是 NoneType 类型的唯一值。判断一个变量是否为 None 时，应使用 is None 而不是 == None
'''